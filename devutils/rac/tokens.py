"""Writes rac_tokens.css from rac_tokens.h, or checks that they match.

rac_tokens.h is the only source: it's what the compiler sees, so the native
values can't drift from it, and the CSS is the one derived file. Springs
become CSS linear() curves sampled from the same spring math as rac::Spring.

By default both files are read from the build tree. Without one, use
`--check --patches patches`: it reads both files from the rac patch that
creates them, and fails if a later patch edits either one.

usage: tokens.py [--check] [-t <build/src> | --patches <dir>]
                 [--header <file>] [--css <file>]
"""

from pathlib import Path
import argparse
import difflib
import math
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
HEADER = Path('chrome/browser/ui/views/rac/rac_tokens.h')
CSS = Path('ui/webui/resources/css/rac_tokens.css')

# A CSS spring ends once it's this close to rest, as a fraction of the move:
# 0.3 px on a 300 px slide.
SPRING_SETTLE = 0.001
# How far the sampled linear() curve may stray from the spring.
SPRING_TOLERANCE = 0.002
SPRING_SAMPLE_SECONDS = 0.0005

# Integer tokens get their CSS unit from their name.
UNITS = [
    ('Radius', 'px'),
    ('Spacing', 'px'),
    ('Inset', 'px'),
    ('Gap', 'px'),
    ('FontSize', 'px'),
    ('FontWeight', ''),
]

COPYRIGHT = """\
/* Copyright 2026 The rac Authors
 * You can use, redistribute, and/or modify this source code under
 * the terms of the GPL-3.0 license that can be found in the LICENSE file. */

/* Generated by devutils/rac/tokens.py from
 * chrome/browser/ui/views/rac/rac_tokens.h. Don't edit it here: change the
 * header and run tokens.py. */
"""

NUMBER = r'-?(?:\d+\.?\d*|\.\d+)(?:[eE]-?\d+)?f?'
STATEMENT = re.compile(r'inline\s+constexpr\s+(?P<type>[\w:]+)\s+(?P<name>k\w+)\s*'
                       r'(?:=\s*(?P<value>.+)|\{(?P<list>.*)\})$', re.S)
DURATION = re.compile(r'base::(?P<unit>Milliseconds|Microseconds|Seconds|Hertz)\(\s*'
                      rf'(?P<n>{NUMBER})\s*\)$')
FUNCTION = re.compile(r'constexpr\s+[\w:]+\s+\w+\([^)]*\)\s*\{[^{}]*\}')
CSS_LINE = re.compile(r'//\s*rac-css:\s*(?P<css>--rac-[\w-]+\s*:[^;]+;)')


class TokenError(ValueError):
    """The header has a token tokens.py can't read."""


class Token:
    """One token: its C++ name and type, its value, and the comment above it."""

    def __init__(self, kind, name, value, comment=''):
        self.kind = kind
        self.name = name
        self.value = value
        self.comment = comment

    def __repr__(self):
        return f'Token({self.kind}, {self.name}, {self.value!r})'


def kebab(name):
    """kEaseFadeOut -> ease-fade-out, kRadius10 -> radius-10."""
    name = name[1:] if name.startswith('k') else name
    name = re.sub(r'(?<=[a-z])(?=[A-Z0-9])|(?<=[0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])', '-', name)
    return name.lower()


def number(text):
    """A C++ number literal as a float."""
    text = text.strip()
    if not re.fullmatch(NUMBER, text):
        raise TokenError(f'not a number: {text}')
    return float(text.rstrip('fF'))


def split_list(text):
    """Splits a braced list's items at top-level commas."""
    items, depth, current = [], 0, ''
    for char in text:
        if char in '({':
            depth += 1
        elif char in ')}':
            depth -= 1
        if char == ',' and depth == 0:
            items.append(current.strip())
            current = ''
        else:
            current += char
    if current.strip():
        items.append(current.strip())
    return items


def strip_comments(text):
    """Removes // and /* */ comments, keeping line breaks."""
    text = re.sub(r'/\*.*?\*/', lambda m: '\n' * m.group(0).count('\n'), text, flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


def tokens_region(text):
    """The text inside `namespace tokens { ... }`."""
    start = re.search(r'namespace\s+tokens\s*\{', text)
    end = re.search(r'\}\s*//\s*namespace tokens', text)
    if not start or not end or end.start() < start.end():
        raise TokenError('no `namespace tokens { ... }  // namespace tokens` block')
    return text[start.end():end.start()]


def statements(region):
    """Yields (statement, comment above it, CSS-only lines before it)."""
    comment, css_lines, current = [], [], ''
    for line in region.splitlines():
        stripped = line.strip()
        css = CSS_LINE.match(stripped)
        if css:
            css_lines.append(css.group('css'))
            continue
        if 'rac-css:' in stripped:
            raise TokenError('write a CSS-only line as `// rac-css: --rac-name: value;`, '
                             f'not {stripped}')
        if stripped.startswith('//') and not current:
            comment.append(stripped[2:].strip())
            continue
        if not stripped and not current:
            comment = []
            continue
        current += ' ' + strip_comments(line)
        joined = current.strip()
        function = FUNCTION.fullmatch(joined)
        if function:
            current, comment = '', []
            continue
        if joined.endswith(';') and joined.count('{') == joined.count('}'):
            yield joined[:-1].strip(), ' '.join(comment), css_lines
            current, comment, css_lines = '', [], []
    if current.strip():
        raise TokenError(f'unfinished statement: {current.strip()}')
    if css_lines:
        yield None, '', css_lines


def parse_duration(text, known):
    """A duration in microseconds, from base::Milliseconds(n) and friends."""
    text = text.strip()
    if text in known:
        token = known[text]
        if token.kind != 'duration':
            raise TokenError(f'{text} is not a duration')
        return token.value
    match = DURATION.match(text)
    if not match:
        raise TokenError(f'not a duration: {text}')
    n = number(match.group('n'))
    unit = match.group('unit')
    if unit == 'Hertz':
        if n != int(n) or n <= 0:
            raise TokenError(f'not a whole, positive frequency: {text}')
        # base::Hertz divides whole microseconds, rounding down.
        return 1_000_000 // int(n)
    scale = {'Microseconds': 1, 'Milliseconds': 1000, 'Seconds': 1_000_000}[unit]
    return int(n * scale)


def parse_curve(items):
    if len(items) != 5 or not items[4].startswith('gfx::Tween::'):
        raise TokenError(f'a Curve is {{x1, y1, x2, y2, gfx::Tween::TYPE}}, not {items}')
    return {'bezier': tuple(number(i) for i in items[:4]), 'tween': items[4][len('gfx::Tween::'):]}


def parse_header(text):
    """Returns the header's tokens and CSS-only lines, in order."""
    known = {}
    out = []
    for statement, comment, css_lines in statements(tokens_region(text)):
        out.extend(css_lines)
        if statement is None:
            continue
        match = STATEMENT.match(statement)
        if not match:
            raise TokenError(f'not a token: {statement}')
        kind, name = match.group('type'), match.group('name')
        value, items = match.group('value'), match.group('list')
        if name in known:
            raise TokenError(f'{name} is defined twice')
        if value is not None and value.strip() in known:
            alias = known[value.strip()]
            token = Token(alias.kind, name, alias.value, comment)
            token.alias = alias.name
        else:
            token = Token(None, name, None, comment)
            token.alias = None
            token.kind, token.value = read_value(kind, name, value, items, known)
        known[name] = token
        out.append(token)
    return out


def read_value(kind, name, value, items, known):
    """The (kind, value) of a token declared as `kind name = value` or `{items}`."""
    parts = split_list(items) if items is not None else None
    if kind == 'base::TimeDelta' and value is not None:
        return 'duration', parse_duration(value, known)
    if kind == 'Curve' and parts is not None:
        return 'curve', parse_curve(parts)
    if kind == 'Timing' and parts is not None and len(parts) == 2:
        curve = parts[1]
        if curve in known and known[curve].kind == 'curve':
            return 'timing', {
                'duration': parse_duration(parts[0], known),
                'curve': known[curve].value,
                'curve_name': curve
            }
        return 'timing', {
            'duration': parse_duration(parts[0], known),
            'curve': parse_curve(split_list(curve.strip('{} '))),
            'curve_name': None
        }
    if kind == 'Spring' and parts is not None and len(parts) == 2:
        response, ratio = number(parts[0]), number(parts[1])
        if response <= 0 or ratio <= 0:
            raise TokenError(f'{name}: a spring needs a positive response and ratio')
        return 'spring', (response, ratio)
    if kind == 'RestRule' and parts is not None and len(parts) == 4:
        return 'rest', (number(parts[0]), number(parts[1]), parse_duration(
            parts[2], known), parse_duration(parts[3], known))
    if kind == 'int' and value is not None:
        n = number(value)
        if n != int(n):
            raise TokenError(f'{name}: not a whole number: {value}')
        return 'int', int(n)
    raise TokenError(f'{name}: tokens.py can\'t read a {kind} written that way')


def spring_value(response, ratio, t):
    """Progress of a unit move from rest; the closed forms of rac::Spring."""
    w = 2 * math.pi / response
    if abs(ratio - 1) < 1e-9:
        return 1 - (1 + w * t) * math.exp(-w * t)
    if ratio < 1:
        wd = w * math.sqrt(1 - ratio * ratio)
        return 1 - math.exp(-ratio * w * t) * (math.cos(wd * t) +
                                                 ratio * w / wd * math.sin(wd * t))
    root = math.sqrt(ratio * ratio - 1)
    r1, r2 = -w * (ratio - root), -w * (ratio + root)
    c1 = -r2 / (r1 - r2)
    return 1 - (c1 * math.exp(r1 * t) + (1 - c1) * math.exp(r2 * t))


def spring_settle_ms(response, ratio, epsilon=SPRING_SETTLE):
    """Whole milliseconds after which the move stays within `epsilon` of 1."""
    step, t, last_far = SPRING_SAMPLE_SECONDS / 5, 0.0, 0.0
    limit = 20 * response
    while t < limit:
        if abs(1 - spring_value(response, ratio, t)) > epsilon:
            last_far = t
        t += step
    return math.ceil((last_far + step) * 1000)


def spring_points(response, ratio):
    """(duration in ms, [(progress, value)]) for a CSS linear() curve."""
    duration_ms = spring_settle_ms(response, ratio)
    count = round(duration_ms / 1000 / SPRING_SAMPLE_SECONDS)
    samples = [(i / count, spring_value(response, ratio, i / count * duration_ms / 1000))
               for i in range(count + 1)]
    samples[-1] = (1.0, 1.0)
    # Keep the fewest points whose straight lines stay within the tolerance.
    kept = [samples[0]]
    anchor = 0
    end = 2
    while end < len(samples):
        x0, y0 = samples[anchor]
        x1, y1 = samples[end]
        within = all(
            abs(y0 + (y1 - y0) * (samples[i][0] - x0) / (x1 - x0) - samples[i][1]) <=
            SPRING_TOLERANCE for i in range(anchor + 1, end))
        if within:
            end += 1
            continue
        anchor = end - 1
        kept.append(samples[anchor])
        end = anchor + 2
    kept.append(samples[-1])
    return duration_ms, kept


def css_number(value, places=4):
    text = f'{value:.{places}f}'.rstrip('0').rstrip('.')
    return '0' if text in ('-0', '') else text


def css_ms(microseconds):
    return css_number(microseconds / 1000, 3) + 'ms'


def css_bezier(curve):
    return 'cubic-bezier(' + ', '.join(css_number(v) for v in curve['bezier']) + ')'


def css_linear(points):
    parts = []
    for i, (x, y) in enumerate(points):
        if i in (0, len(points) - 1):
            parts.append(css_number(y))
        else:
            parts.append(f'{css_number(y)} {css_number(x * 100, 2)}%')
    return 'linear(' + ', '.join(parts) + ')'


def unit_for(name):
    for prefix, unit in UNITS:
        if name[1:].startswith(prefix):
            return unit
    raise TokenError(f'{name}: no CSS unit for this name; start it with one of '
                     + ', '.join(p for p, _ in UNITS))


def css_properties(token):
    """[(property, value)] for one token. Rest rules have no CSS."""
    name = kebab(token.name)
    alias = getattr(token, 'alias', None)
    if token.kind == 'curve':
        return [(f'--rac-{name}', css_bezier(token.value))]
    if token.kind == 'duration':
        return [(f'--rac-duration-{name}', css_ms(token.value))]
    if token.kind == 'timing':
        curve = token.value['curve_name']
        ease = f'var(--rac-{kebab(curve)})' if curve else css_bezier(token.value['curve'])
        if alias:
            return [(f'--rac-duration-{name}', css_ms(token.value['duration'])),
                    (f'--rac-motion-{name}', f'var(--rac-motion-{kebab(alias)})')]
        return [(f'--rac-duration-{name}', css_ms(token.value['duration'])),
                (f'--rac-motion-{name}', f'var(--rac-duration-{name}) {ease}')]
    if token.kind == 'spring':
        duration_ms, points = spring_points(*token.value)
        return [(f'--rac-{name}-duration', f'{duration_ms}ms'),
                (f'--rac-{name}-easing', css_linear(points)),
                (f'--rac-{name}', f'var(--rac-{name}-duration) var(--rac-{name}-easing)')]
    if token.kind == 'int':
        if alias:
            return [(f'--rac-{name}', f'var(--rac-{kebab(alias)})')]
        return [(f'--rac-{name}', f'{token.value}{unit_for(token.name)}')]
    return []


def wrap_comment(text, indent='  ', width=80):
    words, lines, line = text.split(), [], ''
    for word in words:
        if len(indent) + 3 + len(line) + 1 + len(word) + 3 > width and line:
            lines.append(line)
            line = word
        else:
            line = f'{line} {word}'.strip()
    lines.append(line)
    if len(lines) == 1:
        return [f'{indent}/* {lines[0]} */']
    return ([f'{indent}/* {lines[0]}'] + [f'{indent} * {l}' for l in lines[1:-1]] +
            [f'{indent} * {lines[-1]} */'])


def render_css(items):
    """The whole rac_tokens.css for parsed header items."""
    out = [COPYRIGHT, ':root {']
    for item in items:
        if isinstance(item, str):
            out.append('  ' + re.sub(r'\s*:\s*', ': ', item, count=1))
            continue
        properties = css_properties(item)
        if not properties:
            continue
        if item.comment:
            out.extend(wrap_comment(item.comment))
        for prop, value in properties:
            out.append(f'  {prop}: {value};')
    out.append('}')
    return '\n'.join(out) + '\n'


def new_file_from_patches(patches, path):
    """The contents of `path` as created by a patch under `patches`, or None.

    Fails if another patch edits the file, since only the creation is read.
    """
    # quilt writes `b/` paths with rac's settings and `src/` without them.
    targets = tuple(f'+++ {prefix}/{path.as_posix()}' for prefix in ('b', 'src'))
    created = None
    for patch in sorted(Path(patches).rglob('*.patch')):
        lines = patch.read_text(encoding='utf-8', errors='replace').splitlines()
        for i, line in enumerate(lines):
            if line.split('\t')[0] not in targets:
                continue
            if i == 0 or not lines[i - 1].startswith('--- /dev/null'):
                # Only the creating patch is read, so an edit would go unseen.
                raise TokenError(f'{patch.name} edits {path}; check in a build tree '
                                 'or fold the edit into the patch that creates it')
            if created is not None:
                raise TokenError(f'two patches create {path}')
            body = []
            for line_after in lines[i + 2:]:
                if line_after.startswith('+'):
                    body.append(line_after[1:])
                elif line_after.startswith('\\'):
                    continue
                else:
                    break
            created = '\n'.join(body) + '\n'
    return created


def main():
    """CLI entrypoint"""
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='fail if the CSS is out of date')
    parser.add_argument('-t', metavar='source_tree', type=Path, default=ROOT / 'build' / 'src')
    parser.add_argument('--patches', type=Path, help='read both files from these patches')
    parser.add_argument('--header', type=Path, help='rac_tokens.h to read')
    parser.add_argument('--css', type=Path, help='rac_tokens.css to write or check')
    args = parser.parse_args()

    try:
        if args.patches:
            header_text = new_file_from_patches(args.patches, HEADER)
            css_text = new_file_from_patches(args.patches, CSS)
            if header_text is None:
                sys.exit(f'tokens: no patch under {args.patches} creates {HEADER}')
            if not args.check:
                sys.exit('tokens: --patches only checks; write the CSS in a build tree')
            css_path = f'{args.patches}:{CSS}'
        else:
            header = args.header or args.t / HEADER
            css = args.css or args.t / CSS
            header_text = header.read_text(encoding='utf-8')
            css_text = css.read_text(encoding='utf-8') if css.exists() else None
            css_path = str(css)
        expected = render_css(parse_header(header_text))
    except (OSError, TokenError) as error:
        sys.exit(f'tokens: {error}')

    if args.check:
        if css_text == expected:
            return
        diff = difflib.unified_diff((css_text or '').splitlines(keepends=True),
                                    expected.splitlines(keepends=True),
                                    fromfile=css_path,
                                    tofile='expected')
        sys.stdout.writelines(diff)
        sys.exit('tokens: rac_tokens.css is out of date; run devutils/rac/tokens.py')
    css.write_text(expected, encoding='utf-8')


if __name__ == '__main__':
    main()
